"""The identifiers a pilot's README names must resolve in its committed fixture (TC-521).

Data driven over all 40 committed ``api_surface.json`` fixtures. The gaps that exist today are on an
exact allowlist (``tests/fixtures/readme_identifier_allowlist.json``, generated by the helper, never
edited by hand): a new gap fails, and so does a listed gap that has since been fixed (the
stale-allowlist rule, like TC-440's tex_python exception).
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from tests.extraction import docs_identifiers as helper


def test_there_are_forty_pilots() -> None:
    assert len(helper.PILOTS) == 40


@pytest.mark.parametrize("pilot", helper.PILOTS)
def test_allowlist_matches_the_current_gaps(pilot: str) -> None:
    new_gaps, stale = helper.compare(pilot)
    assert (new_gaps, stale) == (set(), set()), (
        f"{pilot}: the README names {sorted(new_gaps)} which the committed fixture does not hold "
        "(fix the extraction, or add each name to tests/fixtures/readme_identifier_allowlist.json with a "
        f"reason via `python -m tests.extraction.docs_identifiers --write`); {sorted(stale)} are on the "
        "allowlist but now resolve or are no longer named (REMOVE them)."
    )


def test_every_allowlist_pilot_is_a_real_pilot() -> None:
    assert set(helper.load_allowlist()) <= set(helper.PILOTS)


def test_allowlist_file_is_canonical(tmp_path: Path) -> None:
    rewritten = helper.write_allowlist(tmp_path / "allowlist.json")
    committed = helper.ALLOWLIST_PATH.read_bytes()
    assert rewritten.read_bytes() == committed
    assert committed.endswith(b"\n")
    assert b"\r" not in committed
    assert not committed.startswith(b"\xef\xbb\xbf")
    data = json.loads(committed)
    assert list(data) == sorted(data)
    assert all(names == sorted(names) and names for names in data.values())


def test_the_whole_check_passes_and_the_cli_agrees() -> None:
    helper.assert_docs_identifiers_resolve()
    assert helper.main([]) == 0


def test_a_new_gap_is_reported() -> None:
    fixture = {"types": [{"name": "Widget", "class_import": "pkg.Widget", "methods": [{"name": "open"}]}]}
    documented = {"Widget", "open", "fooBar"}
    unresolved_names = documented - helper.known_names_of(fixture)
    assert unresolved_names == {"fooBar"}
    new_gaps, stale = helper.compare_sets(unresolved_names, [])
    assert new_gaps == {"fooBar"}
    assert stale == set()


def test_a_fixed_gap_left_on_the_allowlist_is_reported() -> None:
    fixture = {"types": [{"name": "Widget", "methods": [{"name": "fooBar"}]}]}
    documented = {"Widget", "fooBar"}
    unresolved_names = documented - helper.known_names_of(fixture)
    assert unresolved_names == set()
    new_gaps, stale = helper.compare_sets(unresolved_names, ["fooBar"])
    assert new_gaps == set()
    assert stale == {"fooBar"}


def test_a_name_the_readme_no_longer_mentions_is_stale_too() -> None:
    assert helper.compare_sets(set(), ["gone"]) == (set(), {"gone"})


def test_the_failure_message_says_what_to_do(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(helper, "load_allowlist", lambda: {"jmap_nodejs": ["stale_entry_x"]})
    monkeypatch.setattr(helper, "unresolved", lambda pilot: {"newGapY"})
    with pytest.raises(AssertionError) as raised:
        helper.assert_docs_identifiers_resolve(["jmap_nodejs"])
    message = str(raised.value)
    assert "jmap_nodejs" in message
    assert "newGapY" in message and "add the name to the allowlist" in message
    assert "stale_entry_x" in message and "REMOVE" in message


def test_known_names_include_types_import_segments_and_members() -> None:
    fixture = {
        "types": [
            {
                "name": "Color",
                "class_import": "pkg::ns::Color",
                "methods": [{"name": "toHex"}],
                "properties": [{"name": "alpha"}],
                "enum_members": [{"name": "Red"}],
            },
            {"name": "util", "class_import": "a/b/util"},
        ]
    }
    assert helper.known_names_of(fixture) == {"Color", "toHex", "alpha", "Red", "util"}


