def test_docs_identifiers_reads_spans_not_fences(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    pages = tmp_path / "furnished" / "demo" / "pages"
    pages.mkdir(parents=True)
    (pages / "_index.md").write_text(
        "Call `client.listMailboxes()` and `pip` first.\n\n"
        "```js\n`insideFence` is code\n```\n\n"
        "Not an identifier: `a b c` and `not-ident`.\n",
        encoding="utf-8",
    )
    monkeypatch.setattr(helper, "FIXTURES", tmp_path)
    assert helper.docs_identifiers("demo") == {"listMailboxes"}


def test_jmap_nodejs_mixin_methods_are_a_listed_gap() -> None:
    """Documents today's gap: the committed jmap_nodejs fixture predates the mixin extraction.

    The day a re-extraction card regenerates jmap_nodejs this fails, and that card must regenerate the
    allowlist (``python -m tests.extraction.docs_identifiers --write``) so these names leave it.
    """
    gaps = {"listMailboxes", "createMailbox", "cancelSend"}
    assert gaps <= set(helper.load_allowlist()["jmap_nodejs"])
    assert gaps <= helper.unresolved("jmap_nodejs")
