"""Extraction of documentation candidates from a furnished-content page's
own overview/content/faq front matter.

This module performs pure extraction only: it turns an already-parsed
furnished page (a Hugo page-bundle dict) into structured ``DocCandidate``
records, mirroring ``example_candidates.py``'s own already-accepted
``extract_candidate_examples``/``CandidateExample`` shape (TC-066) exactly.
It does not verify, classify, chunk, or index anything — that happens
downstream, in ``normalization``/``indexing`` stages this card does not own.

Extraction is confirmed, by real per-pilot tests against real furnished
fixtures, across all 6 pilots: ``pdf_net``, ``pdf_java``, ``pdf_typescript``,
``pdf_go``, ``cells_rust``, and ``slides_python`` (see
``tests/fixtures/furnished/<pilot>/pages/_index.md`` and
``tests/indexing/test_doc_candidates.py``).

Two conventions here are load-bearing, not decorative:

* **The FAQ prefix.** ``search_docs.classify_content_type`` only buckets a
  chunk's ``content_type`` as ``"faq"`` when the chunk's own persisted text
  contains the literal substring ``"faq"`` or ``"frequently asked"`` (see
  ``foss_mcp.mcp.tools.search_docs._CONTENT_TYPE_HINTS``). A real FAQ
  answer's own prose typically contains neither word. Without an explicit
  marker, every FAQ candidate would silently misclassify as
  ``developer_guide`` (the classifier's own default) and the ``faq``
  content_type would stay permanently empty even where real FAQ content
  exists. So every FAQ-origin candidate's body is formatted EXACTLY as
  ``f"FAQ: {question}\\n\\n{answer}"`` — this prefix supplies the literal
  substring ``"faq"`` the classifier requires.

* **No synthetic heading.** ``foss_mcp.normalization.chunker.chunk_document``
  splits a body on markdown ``#``-style heading syntax and MOVES the heading
  text into ``Chunk.section_title``, DROPPING it from ``Chunk.text`` — and
  ``classify_content_type`` only ever inspects the persisted ``text`` field
  (``build_lexical_index`` never persists ``content_type`` or
  ``section_title``, only ``text``/``tokens``/``chunk_id``). Adding a
  synthetic ``#`` heading to a candidate's body would therefore silently
  remove real classification signal by moving it somewhere the classifier
  never looks. Every ``DocCandidate.body`` here is left as raw,
  heading-free prose so ``chunk_document``'s own paragraph-splitting path
  handles it.

* **A README section keeps its own heading (G3/TC-817).** ``infra/build_chunks.py`` titles every chunk
  of a candidate ``FQN: Doc: <candidate title>``, and ``classify_content_type`` buckets a chunk from
  that title alone. A furnished page folds README sections it has no block for under one block, as
  ``### <heading>`` subsections of "Key Capabilities" (``generate_furnished_page._apply_section_fallback``)
  or of "Key Capabilities and API Reference" (the older pages), so a section such as words/net's
  "What's not included (and where to get it)" became chunks titled "Key Capabilities" and filed as
  ``developer_guide``: it could never be found as ``troubleshooting``. A ``content`` block's
  section whose own heading names a limitation, or an installation / quick-start step, while the
  block's title names neither is therefore carved out into its own candidate (``_carve_sections``).
  Every other block, and every other section of a carved block, is extracted exactly as before.
"""

from __future__ import annotations

import re
from collections.abc import Mapping
from dataclasses import dataclass

__all__ = ["DocCandidate", "extract_doc_sections"]

# The two buckets a README section heading can reveal. Each pattern is a SUBSET of the matching
# ``search_docs`` title rule (``_TROUBLESHOOTING_TITLE`` / ``_GETTING_STARTED_TITLE``), widened only by
# the "not included" family, which that rule does not know: a carved candidate's title always carries a
# word the classifier does match (``_carved_title``), so the bucket never depends on this widening.
_LIMITATION_HEADING = re.compile(
    r"limitation|unsupported|known issue|troubleshoot"
    r"|\bnot (?:yet )?(?:included|supported|available|implemented|covered)\b"
    r"|\b(?:does|do|did)(?: not|n['’]t) (?:support|include|cover|implement)\b"
    r"|\b(?:cannot|can['’]t|unable to)\b|\bout of scope\b|\bwhat(?:['’]s| is) missing\b",
    re.IGNORECASE,
)
_SETUP_HEADING = re.compile(r"install|quick ?start|getting started", re.IGNORECASE)
# A carved section shorter than this is a heading and a sentence, never a retrievable chunk of its own.
# It happens on a page whose README hierarchy was flattened (every ``##`` section and its ``###``
# children all became ``###``): the section's heading is then followed by its children as SIBLINGS, so
# its own text is only the lead-in. Such a section stays inside its block, exactly as before, rather
# than become a stub chunk (a page regenerated by ``generate_furnished_page`` keeps the children nested).
_MIN_CARVED_CHARS = 200
_LIMITATIONS = "limitations"
_GETTING_STARTED = "getting_started"
_FENCE_OPENER = re.compile(r"^[ \t]{0,3}(`{3,}|~{3,})")
_ATX_HEADING = re.compile(r"^ {0,3}(#{1,6})[ \t]+(.+?)(?:[ \t]+#+)?[ \t]*$")


@dataclass(frozen=True)
class DocCandidate:
    """A single, not-yet-indexed documentation candidate extracted from a
    furnished page's own overview/content/faq front matter.

    ``origin`` is one of ``"overview"``, ``"content"``, or ``"faq"``, for
    traceability only — it is not consulted by any downstream classification
    logic.
    """

    title: str
    body: str
    origin: str


def _is_enabled(section: object) -> bool:
    return isinstance(section, Mapping) and section.get("enable") is True


def _extract_overview(page: Mapping[str, object]) -> list[DocCandidate]:
    overview = page.get("overview")
    if not _is_enabled(overview):
        return []
    assert isinstance(overview, Mapping)  # narrowed by _is_enabled
    title = overview.get("title")
    content = overview.get("content")
    if not isinstance(title, str) or not isinstance(content, str):
        return []
    return [DocCandidate(title=title, body=content, origin="overview")]


def _heading_bucket(heading: str) -> str | None:
    """``"limitations"`` / ``"getting_started"`` when *heading* names one of them, else ``None``."""
    if _LIMITATION_HEADING.search(heading):
        return _LIMITATIONS
    if _SETUP_HEADING.search(heading):
        return _GETTING_STARTED
    return None


def _carved_title(heading: str, bucket: str) -> str:
    """The candidate title for a carved section: its own heading, made to classify as *bucket*.

    The heading alone is kept when it already holds a word the classifier's title rule matches; any
    other (``What's not included (and where to get it)``) is prefixed with the bucket's own name.
    """
    if bucket == _LIMITATIONS:
        if re.search(r"limitation|unsupported|known issue|troubleshoot", heading, re.IGNORECASE):
            return heading
        return f"Scope and Limitations: {heading}"
    if _SETUP_HEADING.search(heading):
        return heading
    return f"Getting Started: {heading}"  # pragma: no cover - _SETUP_HEADING is what chose the bucket


def _section_headings(lines: list[str]) -> list[tuple[int, int, str]]:
    """``(line index, level, text)`` of every ATX heading of *lines* outside a fenced code block."""
    headings: list[tuple[int, int, str]] = []
    marker: str | None = None
    for index, line in enumerate(lines):
        if marker is not None:
            stripped = line.strip()
            if len(stripped) >= len(marker) and set(stripped) == {marker[0]}:
                marker = None
            continue
        opener = _FENCE_OPENER.match(line)
        if opener is not None:
            marker = opener.group(1)
            continue
        match = _ATX_HEADING.match(line)
        if match is not None:
            headings.append((index, len(match.group(1)), match.group(2).strip()))
    return headings


def _carve_sections(title: str, body: str) -> list[tuple[str, str]]:
    """``[(title, body)]`` of one content block: the block itself (when anything is left of it) first, then
    each section carved out of it, in body order.

    A section is carved out when it sits at the body's shallowest heading level, its heading names a
    bucket (``_heading_bucket``) and the block's own title does not name that same bucket. The carved
    section's body is the text under its heading (the heading is its title now), with each nested heading
    kept as a bold line: ``chunk_document`` would otherwise cut the section at them, drop their text and
    strand the lead-in paragraph as a chunk of its own. A block with nothing to carve comes back unchanged.
    """
    lines = body.split("\n")
    headings = _section_headings(lines)
    if not headings:
        return [(title, body)]
    top_level = min(level for _, level, _ in headings)
    own_bucket = _heading_bucket(title)
    carved: list[tuple[str, str]] = []
    kept = list(lines)
    # Reverse order, so removing a carved range never shifts a range still to be removed.
    for position in range(len(headings) - 1, -1, -1):
        start, level, heading = headings[position]
        bucket = _heading_bucket(heading)
        if level != top_level or bucket is None or bucket == own_bucket:
            continue
        stop = next((index for index, lv, _ in headings[position + 1 :] if lv <= level), len(lines))
        nested = {index: text for index, _, text in headings[position + 1 :] if index < stop}
        section = [
            f"**{nested[index]}**" if index in nested else lines[index] for index in range(start + 1, stop)
        ]
        text = "\n".join(section).strip("\n")
        if len(text) < _MIN_CARVED_CHARS:
            continue  # a lead-in line, not a section: its siblings are the content (see _MIN_CARVED_CHARS)
        carved.append((_carved_title(heading, bucket), text))
        del kept[start:stop]
    if not carved:
        return [(title, body)]
    carved.reverse()
    remainder = "\n".join(kept).strip("\n")
    return ([(title, remainder)] if remainder.strip() else []) + carved


def _extract_content_blocks(page: Mapping[str, object]) -> list[DocCandidate]:
    content_section = page.get("content")
    if not _is_enabled(content_section):
        return []
    assert isinstance(content_section, Mapping)  # narrowed by _is_enabled
    blocks = content_section.get("block", [])
    if not isinstance(blocks, list):
        return []

    candidates: list[DocCandidate] = []
    for block in blocks:
        if not isinstance(block, Mapping):
            continue
        title_left = block.get("title_left")
        content_left = block.get("content_left")
        if isinstance(title_left, str) and isinstance(content_left, str):
            for title, body in _carve_sections(title_left, content_left):
                candidates.append(DocCandidate(title=title, body=body, origin="content"))

        title_right = block.get("title_right")
        content_right = block.get("content_right")
        if isinstance(title_right, str) and isinstance(content_right, str):
            for title, body in _carve_sections(title_right, content_right):
                candidates.append(DocCandidate(title=title, body=body, origin="content"))

    return candidates


def _extract_faq(page: Mapping[str, object]) -> list[DocCandidate]:
    faq = page.get("faq")
    if not _is_enabled(faq):
        return []
    assert isinstance(faq, Mapping)  # narrowed by _is_enabled
    entries = faq.get("list", [])
    if not isinstance(entries, list):
        return []

    candidates: list[DocCandidate] = []
    for entry in entries:
        if not isinstance(entry, Mapping):
            continue
        question = entry.get("question")
        answer = entry.get("answer")
        if not isinstance(question, str) or not isinstance(answer, str):
            continue
        candidates.append(
            DocCandidate(
                title=question,
                body=f"FAQ: {question}\n\n{answer}",
                origin="faq",
            )
        )

    return candidates


def extract_doc_sections(page: Mapping[str, object]) -> list[DocCandidate]:
    """Extract documentation candidates from an already-parsed furnished page dict.

    ``page`` is the dict produced by ``yaml.safe_load`` on the front-matter
    block of a furnished-content page bundle (never a file path — callers
    load and parse the page themselves).

    Three sections are inspected, each independently and gracefully skipped
    when absent, disabled, or malformed (mirroring
    ``extract_candidate_examples``'s own defensive ``isinstance``/missing-key
    handling — never an error):

    * ``overview`` — one candidate when ``overview.enable`` is ``True``,
      with ``title=overview["title"]`` and ``body=overview["content"]``.
    * ``content`` — two candidates per entry of ``content.block[]`` when
      ``content.enable`` is ``True``: one from
      ``title_left``/``content_left``, one from
      ``title_right``/``content_right``.
    * ``faq`` — one candidate per entry of ``faq.list[]`` when
      ``faq.enable`` is ``True``, with ``body`` formatted as
      ``f"FAQ: {question}\\n\\n{answer}"`` (see module docstring for why).
    """
    candidates: list[DocCandidate] = []
    candidates.extend(_extract_overview(page))
    candidates.extend(_extract_content_blocks(page))
    candidates.extend(_extract_faq(page))
    return candidates
